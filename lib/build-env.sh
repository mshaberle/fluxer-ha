# Builds .env from fluxer-ha/.env.shared (identical on both sites) and fluxer-ha/.env.site (this
# host only). Refuses to build if any key appears more than once, so a
# per-site value can't silently shadow a shared one, or the reverse.
set -eu
cd "$(dirname "$0")/.."

for f in fluxer-ha/.env.shared fluxer-ha/.env.site; do
	[ -f "$f" ] || { echo "missing $f" >&2; exit 1; }
done

# Refuse to overwrite edits made straight to the generated .env. Upstream's
# `install.sh --update` writes a newly required secret there (fluxer_env_set:
# FLUXER_ERLANG_COOKIE, FLUXER_MEDIA_PROXY_UPLOAD_RELAY_SECRET_BASE64,
# FLUXER_PROFILE_PSEUDONYM_SECRET when missing or CHANGE_ME). Rebuilding would
# lose it, and two sites would each mint a different one.
# Each build records a sha256 of every line it wrote (hashes only, no values)
# in .env.built next to this script. A line of .env that isn't in that record
# was written by something else. Comparing with fluxer-ha/.env.shared instead would flag
# every legitimate edit of fluxer-ha/.env.shared too (lab: the etcd upgrade).
BUILT=$(dirname "$0")/.env.built
line_sums() { grep -E '^[A-Za-z_][A-Za-z0-9_]*=' "$1" | while IFS= read -r l; do printf '%s %s\n' "${l%%=*}" "$(printf '%s' "$l" | sha256sum | cut -c1-64)"; done | sort; }
if [ -f .env ] && [ -f "$BUILT" ] && [ "${1:-}" != --discard-env-edits ]; then
	# Lines this script didn't write, and that the sources don't hold either
	# (once you've moved a key into fluxer-ha/.env.shared, it's no longer an edit).
	srcs=$(mktemp); cat fluxer-ha/.env.shared fluxer-ha/.env.site >"$srcs"
	edited=$(line_sums .env | comm -23 - "$BUILT" | comm -23 - "$(line_sums "$srcs" >"$srcs.sums"; echo "$srcs.sums")" | cut -d' ' -f1 | sort -u)
	rm -f "$srcs" "$srcs.sums"
	if [ -n "$edited" ]; then
		echo "refusing: these keys in .env were written by something other than this script" >&2
		echo "(install.sh --update does that, for new secrets):" >&2
		echo "$edited" | sed 's/^/  /' >&2
		echo "Copy each into fluxer-ha/.env.shared on BOTH sites with the same value (or into fluxer-ha/.env.site if it" >&2
		echo "belongs to this site only), then run this again. To throw them away: $0 --discard-env-edits" >&2
		exit 1
	fi
fi

dupes=$(cat fluxer-ha/.env.shared fluxer-ha/.env.site | sed -n 's/^\([A-Za-z_][A-Za-z0-9_]*\)=.*/\1/p' | sort | uniq -d)
if [ -n "$dupes" ]; then
	echo "refusing: keys defined more than once:" >&2
	echo "$dupes" >&2
	exit 1
fi

# Keep the owner .env already has: upstream's installer runs as a normal user
# in the docker group, who should still be able to run `docker compose`.
# With no .env yet (site 2 before join), take fluxer-ha/.env.shared's owner.
owner=$(stat -c %u:%g .env 2>/dev/null || stat -c %u:%g fluxer-ha/.env.shared)
umask 077
{
	echo "# GENERATED by fluxer-ha/build-env.sh. Edit fluxer-ha/.env.shared or fluxer-ha/.env.site instead."
	cat fluxer-ha/.env.shared
	echo
	cat fluxer-ha/.env.site
} > .env.tmp
chown "$owner" .env.tmp
mv .env.tmp .env
line_sums .env >"$BUILT.tmp" && mv "$BUILT.tmp" "$BUILT"

echo ".env rebuilt. Compare this hash with the other site:"
sha256sum fluxer-ha/.env.shared
