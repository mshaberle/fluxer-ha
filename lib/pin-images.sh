#
# Writes fluxer-ha/ha.images.lock.yml: a Compose overlay that sets every service's
# image to the exact digest this host has pulled. Add it LAST to COMPOSE_FILE
# and copy it, byte for byte, to the other site. ha-health.sh compares it
# between sites along with fluxer-ha/.env.shared.
#
# Why: Fluxer's images all take one tag (FLUXER_IMAGE_TAG, default v1, which
# moves), and there is no stack-wide release tag (F4). Two sites pulling at
# different times can run different code. A digest can't move.
#
# Upgrade (docs/operations.md, "Upgrades"):
#   1. fluxer-ha/pin-images.sh --pull   on one site: pulls what the tags point at NOW
#                                (ignoring the old lock, which would pull the
#                                old digests), then writes the new lock
#   2. copy fluxer-ha/ha.images.lock.yml to the other site and run
#      `docker compose --profile app pull` there: it fetches exactly those digests
#   3. roll out as docs/operations.md, "Upgrades" describes
#
# Pinning is optional. Without fluxer-ha/ha.images.lock.yml in COMPOSE_FILE (and the
# file absent on both sites) the stack runs the tags as they are, and the
# drift check compares fluxer-ha/.env.shared alone.
#
# Services that are built locally (postgres -> fluxer-patroni:local) are
# skipped. Needs jq.
set -eu
cd "$(dirname "$0")/.."

OUT=fluxer-ha/ha.images.lock.yml
command -v jq >/dev/null || { echo "pin-images: needs jq" >&2; exit 1; }

# Resolve the config WITHOUT any existing lock, so its pins don't feed back in.
cf=$(sed -n 's/^COMPOSE_FILE=//p' .env | tail -n 1 | tr ':' '\n' | grep -vx "$OUT" | paste -sd: -)
# printf, not echo: dash's echo turns the JSON's \n and \t escapes into raw
# characters, which jq then rejects (lab).
if [ "${1:-}" = --pull ]; then
	COMPOSE_FILE=$cf docker compose --profile app pull --ignore-buildable
fi
cfg=$(COMPOSE_FILE=$cf docker compose --profile app config --format json)
list=$(printf '%s\n' "$cfg" | jq -r '.services | to_entries[] | select(.value.build == null and .value.image != null) | "\(.key) \(.value.image)"' | sort)
[ -n "$list" ] || { echo "pin-images: found no services to pin; nothing written" >&2; exit 1; }

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
{
	echo "# GENERATED by fluxer-ha/pin-images.sh on $(date -u +%FT%TZ) on $(hostname)."
	echo "# Every service's image, pinned by digest. Identical on both sites."
	echo "services:"
} >"$tmp"

echo "$list" | while read -r svc image; do
	case $image in
		*@sha256:*) ref=$image ;;  # already pinned (the HA layer's own images)
		*)
			# Strip the tag, but not a registry port (host:5000/name has no tag).
			case ${image##*:} in */*) repo=$image ;; *) repo=${image%:*} ;; esac
			digest=$(docker image inspect --format '{{range .RepoDigests}}{{println .}}{{end}}' "$image" 2>/dev/null |
				awk -v r="$repo@sha256:" 'index($0, r) == 1' | head -n 1) || true
			if [ -z "$digest" ]; then
				echo "pin-images: $svc: $image is not pulled here (docker compose --profile app pull)" >&2
				echo 1 >"$tmp.missing"
				continue
			fi
			ref="$image@${digest#*@}"
			;;
	esac
	printf '  %s:\n    image: %s\n' "$svc" "$ref" >>"$tmp"
done

if [ -e "$tmp.missing" ]; then rm -f "$tmp.missing"; echo "pin-images: nothing written" >&2; exit 1; fi
mv "$tmp" "$OUT"
chmod 644 "$OUT"
trap - EXIT
echo "pin-images: wrote $OUT ($(grep -c '    image:' "$OUT") services). Copy it to the other site, then:"
sha256sum "$OUT"
